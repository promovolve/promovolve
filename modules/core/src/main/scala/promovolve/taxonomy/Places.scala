package promovolve.taxonomy

import scala.annotation.tailrec
import scala.io.Source
import scala.util.Using

/** What level of the hierarchy a [[Place]] sits at. */
enum PlaceKind:
  case Country, Subdivision, City

/**
 * One node of the geographic vocabulary.
 *
 * `parent` is the code of the enclosing place, never derived by parsing
 * `code`. City codes are opaque GeoNames ids precisely so nobody is
 * tempted to infer structure from the string.
 */
final case class Place(
    code: String,
    name: String, // English, canonical — feeds prompts and matching
    kind: PlaceKind,
    parent: Option[String],
    population: Long = 0L
)

/**
 * The closed geographic vocabulary: countries (ISO 3166-1 alpha-2),
 * first-level subdivisions (ISO 3166-2), and cities (GeoNames ids,
 * prefixed `GN`).
 *
 * Closed is the point. Every geographic value that enters the system —
 * an LLM's answer about what a page is about, a publisher's audience
 * declaration, an advertiser's targeting set — is checked against this
 * table and dropped if absent, so downstream matching is plain set
 * intersection over a vocabulary both sides share. See
 * `docs/design/GEOGRAPHIC_CONTEXT.md`.
 *
 * Tables are generated by `scripts/build-places.sh`; codes come from ISO
 * and cities from GeoNames. The two disagree about subdivision numbering
 * (GeoNames JP.13 is Hyogo, ISO JP-13 is Tokyo), which is why the build
 * links cities to ISO subdivisions by name and leaves `parent` at the
 * country when it cannot match confidently — a coarser answer, never a
 * wrong one.
 */
object Places {

  private val CountriesPath = "/places/countries"
  private val SubdivisionsPath = "/places/subdivisions"
  private val CitiesPath = "/places/cities"
  // Search-only names: every OTHER localised name GeoNames knows for a
  // place (アメリカ beside the catalogue's 米国, ロス beside ロサンゼルス).
  // Many rows per code, never shown — display stays the one curated name.
  private val AliasesPath = "/places/aliases"

  private lazy val byCode: Map[String, Place] = {
    val countries = loadTsv(s"$CountriesPath.tsv", 2) { cols =>
      Place(cols(0), cols(1), PlaceKind.Country, None)
    }
    val subdivisions = loadTsv(s"$SubdivisionsPath.tsv", 3) { cols =>
      Place(cols(0), cols(2), PlaceKind.Subdivision, Some(cols(1)))
    }
    val cities = loadTsv(s"$CitiesPath.tsv", 5) { cols =>
      // admin1 may be blank when the build could not map GeoNames'
      // admin1 onto an ISO subdivision; the city then hangs off its
      // country directly.
      val parent = if (cols(3).nonEmpty) cols(3) else cols(2)
      Place(cols(0), cols(1), PlaceKind.City, Some(parent), cols(4).toLongOption.getOrElse(0L))
    }
    (countries ++ subdivisions ++ cities).map(p => p.code -> p).toMap
  }

  /** Localized display names per compiled-in language, keyed by place code. */
  private lazy val localized: Map[String, Map[String, String]] = {
    val perFile = List(CountriesPath, SubdivisionsPath, CitiesPath).map(LocalizedNames.loadAll)
    LocalizedNames.langs.map { lang =>
      lang -> perFile.foldLeft(Map.empty[String, String])((acc, m) => acc ++ m.getOrElse(lang, Map.empty))
    }.toMap
  }

  /**
   * Search-only aliases, as (code, name) rows.
   *
   * The per-language files are GENERATED by scripts/build-places.sh.
   * `aliases_en.tsv` is the exception: it is hand-maintained, because the
   * everyday English name is exactly what no upstream source carries —
   * iso-codes ships "Korea, Republic of" and there is nothing to merge
   * "South Korea" out of. The build never writes it; see its header.
   */
  private lazy val aliases: Vector[(String, String)] = (LocalizedNames.langs.toVector :+ "en").flatMap(l =>
    loadAliasRows(s"${AliasesPath}_$l.tsv"))

  private def loadAliasRows(resourcePath: String): Vector[(String, String)] =
    Option(getClass.getResourceAsStream(resourcePath)) match {
      case None     => Vector.empty // optional table: search is merely narrower without it
      case Some(is) =>
        Using(Source.fromInputStream(is, "UTF-8")) { source =>
          source
            .getLines()
            .drop(1)
            .filter(_.nonEmpty)
            .map(_.split("\t", -1))
            .collect { case cols if cols.length >= 2 && cols(0).nonEmpty && cols(1).nonEmpty => cols(0) -> cols(1) }
            .toVector
        }.getOrElse(Vector.empty)
    }

  /** Search index: normalized name → codes, built once from every language plus aliases. */
  private lazy val searchIndex: Vector[(String, Place)] = {
    val locales = localized.values.flatten.toVector ++ aliases
    val fromLocal = locales.flatMap { case (code, name) => byCode.get(code).map(p => normalize(name) -> p) }
    val fromEn = byCode.valuesIterator.map(p => normalize(p.name) -> p).toVector
    (fromEn ++ fromLocal).distinct
  }

  /**
   * Places by kind and normalized name (English, every localized name and
   * every alias), for resolving a classifier-emitted NAME to a code.
   * Built from the search index so the picker and the classifier agree on
   * what a name is.
   */
  private lazy val byNameKind: Map[PlaceKind, Map[String, Vector[Place]]] = indexByKind(searchIndex)

  /**
   * Second-chance names DERIVED from the catalogue's own spelling, for
   * when the model writes a place the way people write it and the table
   * carries the way ISO writes it: "Asturias" or "Principado de Asturias"
   * for `Asturias, Principado de`, "Cataluña" for `Catalunya [Cataluña]`.
   *
   * Kept in a SEPARATE index, consulted only after [[byNameKind]] misses,
   * because a derived name may collide with another place's real one —
   * `Congo, The Democratic Republic of the` derives "Congo", which is
   * CG's actual name. Primary wins; the derived collision then resolves
   * to nothing rather than to the wrong country.
   */
  private lazy val derivedNameKind: Map[PlaceKind, Map[String, Vector[Place]]] =
    indexByKind(byCode.valuesIterator.flatMap { p =>
      nameVariants(p.name).map(v => normalize(v) -> p)
    }.toVector)

  private def indexByKind(rows: Vector[(String, Place)]): Map[PlaceKind, Map[String, Vector[Place]]] =
    rows
      .groupBy(_._2.kind)
      .view
      .mapValues(
        _.groupMap(_._1)(_._2).view
          .mapValues(_.distinctBy(_.code).sortBy(p => (-p.population, p.code)))
          .toMap)
      .toMap

  /**
   * Other spellings derivable from ONE catalogue name, with no outside
   * source: bracketed alternates, and the comma-inverted forms ISO uses
   * for a qualified name. Excludes the name itself — that is the primary
   * index's job.
   */
  private[taxonomy] def nameVariants(name: String): Vector[String] = {
    val inBrackets = Bracketed.findAllMatchIn(name).map(_.group(1).trim).toVector
    val plain = Bracketed.replaceAllIn(name, "").replaceAll("\\s+", " ").trim
    val cut = plain.indexOf(',')
    val commaForms =
      if (cut < 0) Vector.empty
      else {
        val head = plain.substring(0, cut).trim
        val qualifier = plain.substring(cut + 1).trim
        Vector(head, s"$qualifier $head")
      }
    (inBrackets ++ commaForms :+ plain).map(_.trim).filter(v => v.nonEmpty && v != name).distinct
  }

  private val Bracketed = "\\[([^\\]]*)\\]".r

  def get(code: String): Option[Place] = byCode.get(code)

  def contains(code: String): Boolean = byCode.contains(code)

  /**
   * Resolve a city NAME to a city code, scoped to the place it sits in.
   *
   * This is the door the design doc left "cheap to open": the classifier
   * can name a town, but the disambiguation that made tier 1 stop at
   * subdivision is done HERE, by scope, not trusted to the model —
   * "Springfield" means nothing, "Springfield, US-IL" means one thing.
   *
   *   - `within` must be a known country or subdivision; the city must
   *     have it as an ancestor.
   *   - Inside a SUBDIVISION several same-named cities are small
   *     townships; the most populous is the one an article is about.
   *   - Inside a COUNTRY the same rule would guess — "Springfield, US" —
   *     so it resolves only when the name is unique there or the largest
   *     is dominant (≥ 5× the runner-up: "Paris, FR", "Kyoto, JP").
   *
   * Localized names count, and a Japanese municipality suffix (市/町/村/区)
   * is tolerated because the tables carry "金沢", not "金沢市". Returns
   * None rather than guessing; the caller falls back to `within`.
   */
  def resolveCity(name: String, within: String): Option[Place] =
    byCode.get(within).filter(_.kind != PlaceKind.City) match {
      case None        => None
      case Some(scope) =>
        lookup(PlaceKind.City, name, Some(within)) match {
          case Vector()                                    => None
          case Vector(single)                              => Some(single)
          case many if scope.kind == PlaceKind.Subdivision => many.headOption
          case many                                        =>
            // Country scope: the largest wins only when it clearly dominates.
            many.headOption.filter(top => top.population >= 5L * many(1).population && top.population > 0L)
        }
    }

  /**
   * Resolve a country NAME to its code. Unique-or-nothing: there is no
   * population tie-break to fall back on at this level, and a guess
   * between two countries is the worst answer available.
   */
  def resolveCountry(name: String): Option[Place] = unique(lookup(PlaceKind.Country, name, None))

  /**
   * Resolve a first-level subdivision NAME within a country.
   *
   * Unique-or-nothing for the same reason as [[resolveCountry]], and
   * because the subdivision table carries no population to rank by. The
   * caller falls back to the country, which is coarser, never wrong.
   */
  def resolveSubdivision(name: String, within: String): Option[Place] =
    if (!byCode.get(within).exists(_.kind == PlaceKind.Country)) None
    else unique(lookup(PlaceKind.Subdivision, name, Some(within)))

  private def unique(candidates: Vector[Place]): Option[Place] =
    candidates match {
      case Vector(single) => Some(single)
      case _              => None
    }

  /**
   * Candidate places of one kind whose name matches `name`, optionally
   * inside `within`.
   *
   * Two orderings are load-bearing. Primary names (the catalogue's own,
   * plus every localized name and alias) are tried before names DERIVED
   * from a catalogue spelling, so a derived form never outranks a real
   * one. And within each index the query is tried as written before its
   * suffix-tolerant variants, so an exact hit is never traded for a
   * fuzzy one.
   */
  private def lookup(kind: PlaceKind, name: String, within: Option[String]): Vector[Place] = {
    val inScope: Place => Boolean =
      within.fold((_: Place) => true)(w => p => ancestors(p.code).exists(_.code == w))
    val keys = queryKeys(name)

    def firstHit(index: Map[PlaceKind, Map[String, Vector[Place]]]): Vector[Place] = {
      val names = index.getOrElse(kind, Map.empty)
      keys.iterator
        .map(k => names.getOrElse(k, Vector.empty).filter(inScope))
        .find(_.nonEmpty)
        .getOrElse(Vector.empty)
    }

    firstHit(byNameKind) match {
      case Vector() => firstHit(derivedNameKind)
      case hit      => hit
    }
  }

  /**
   * Normalized lookup keys for one query name, most literal first.
   *
   * Administrative suffixes are the whole reason this is a list rather
   * than a single key: a model writes "Ishikawa Prefecture" or 石川県
   * while the table carries "Ishikawa"/石川, and the tables are not
   * consistent among themselves either (鎌倉 but 京都市). Over-generating
   * keys is safe — a key that names nothing simply misses, and kind and
   * scope still gate whatever it does find.
   */
  private def queryKeys(name: String): Vector[String] = {
    val bases = (Vector(name.trim) ++ withoutEnglishAdminWord(name)).map(normalize).filter(_.nonEmpty).distinct
    val stripped = bases.flatMap(k =>
      if (k.length > 1 && AdminSuffixes.contains(k.last)) Vector(k.dropRight(1)) else Vector.empty)
    val suffixed = bases.flatMap(k => JapaneseMunicipalitySuffixes.map(k + _))
    (bases ++ stripped ++ suffixed).distinct
  }

  private val JapaneseMunicipalitySuffixes = List("市", "町", "村", "区")

  /**
   * English administrative words a model appends and the table omits.
   * Matched as a trailing WORD, so "Washington" keeps its name while
   * "Washington State" loses the qualifier.
   */
  private val EnglishAdminWords = List(
    "prefecture", "province", "state", "region", "county", "district", "municipality",
    "governorate", "oblast", "krai", "department", "canton", "territory", "emirate")

  private def withoutEnglishAdminWord(name: String): Option[String] = {
    val trimmed = name.trim
    val lower = trimmed.toLowerCase
    EnglishAdminWords.iterator
      .collectFirst { case w if lower.endsWith(s" $w") => trimmed.dropRight(w.length + 1).trim }
      .filter(_.nonEmpty)
  }

  /**
   * One classifier-emitted place → a code, or None when it cannot be
   * read at all.
   *
   *   - `"JP-17"`          → `Some("JP-17")` (a plain code; `validate` is
   *                          still the gate downstream)
   *   - `"Kanazawa, JP-17"` → `Some("GN1860243")` — the city, resolved in
   *                          scope by [[resolveCity]]
   *   - `"Nowhere, JP-17"`  → `Some("JP-17")` — an unresolvable city
   *                          degrades to the place it was said to be in,
   *                          which is coarser, never wrong
   *   - `"Kanazawa, XX-99"` → `None` — no scope to stand on
   *
   * The split is on the LAST comma so a name containing one still reads.
   */
  def resolveEmitted(raw: String): Option[String] = {
    val s = raw.trim
    val cut = s.lastIndexOf(',')
    if (cut < 0) Option(s).filter(_.nonEmpty)
    else {
      val name = s.substring(0, cut).trim
      val within = s.substring(cut + 1).trim.toUpperCase
      if (!contains(within)) None
      else resolveCity(name, within).map(_.code).orElse(Some(within))
    }
  }

  /**
   * One resolved place, plus what could NOT be placed on the way to it.
   *
   * `unresolved` is the point of the type. The old code-shaped answer had
   * exactly one failure mode it could not report — a valid code for the
   * wrong place — because a wrong code and a right one are indis-
   * tinguishable once parsed. Names fail LOUDLY: a region that is not in
   * the stated country, or a city that is not in the stated region, is a
   * contradiction the catalogue can see, and it lands here for the caller
   * to log. The `code` is still the best answer available; this is
   * evidence about it, not a rejection of it.
   */
  final case class ResolvedPlace(code: String, unresolved: List[String])

  /**
   * Resolve a classifier-emitted place given as NAMES — the form the
   * model can actually be accurate in.
   *
   * Nothing here asks the model to recall a code. It names the country,
   * optionally the region, optionally the city, and every code comes out
   * of the shipped table, each level scoped by the one above it:
   * "Ishikawa" is looked up inside Japan, "Kanazawa" inside Ishikawa. The
   * ambiguity that made "Springfield" meaningless is resolved by scope,
   * exactly as it is for [[resolveCity]].
   *
   * Degrades level by level and returns the finest thing it could place:
   * an unresolvable city keeps the region, an unresolvable region keeps
   * the country. An unresolvable COUNTRY is None — with no scope to stand
   * on, the rest cannot be trusted either.
   *
   * The city is tried inside the region and then inside the country,
   * because a real city may hang off its country directly: the build
   * links cities to ISO subdivisions by name and leaves the link empty
   * when it cannot match confidently. Skipping the second try would
   * reject correct answers for a gap in our own table.
   */
  def resolveNamed(city: Option[String], region: Option[String], country: Option[String]): Option[ResolvedPlace] = {
    def named(o: Option[String]): Option[String] = o.map(_.trim).filter(_.nonEmpty)
    val (cityName, regionName, countryName) = (named(city), named(region), named(country))

    countryName.flatMap(resolveCountry).map { stated =>
      val viaRegion = regionName.flatMap(ownCountry(_, stated))
      val viaCity = cityName.filter(resolveCity(_, stated.code).isEmpty).flatMap(ownCountry(_, stated))
      viaRegion.orElse(viaCity) match {
        case Some(own) =>
          // The name that identified the country is used up by it — kept
          // as the city only where it is one too (Macau is both).
          val ownCity = if (viaRegion.isDefined) cityName else cityName.filter(resolveCity(_, own.code).isDefined)
          resolveWithin(own, None, ownCity)
        case None => resolveWithin(stated, regionName, cityName)
      }
    }
  }

  /**
   * Places ISO 3166-2 lists BOTH as a subdivision and as a country of their
   * own: CN-MO and MO are both Macau. Cities hang off the country, and so
   * does an advertiser who targets Macao, so a page about Macau must land on
   * MO even when the model files it under China — as most English text does.
   * Explicit rather than derived from the codes: CN-MO ↔ MO is the same
   * place, but US-IN ↔ IN is Indiana and India.
   */
  private val AlsoCountries: Set[String] = Set(
    "CN-HK", "CN-MO", "CN-TW", "NL-AW", "NL-CW", "NL-SX",
    "US-AS", "US-GU", "US-MP", "US-PR", "US-UM", "US-VI")

  /** The country `name` refers to, when it is one of `within`'s [[AlsoCountries]]. */
  private def ownCountry(name: String, within: Place): Option[Place] =
    resolveSubdivision(name, within.code).map(_.code)
      .orElse(resolveCountry(name).map(c => s"${within.code}-${c.code}"))
      .filter(AlsoCountries)
      .flatMap(sub => byCode.get(sub.drop(within.code.length + 1)))

  private def resolveWithin(countryPlace: Place, regionName: Option[String], cityName: Option[String])
      : ResolvedPlace = {
    val sub = regionName.flatMap(n => resolveSubdivision(n, countryPlace.code))
    val inSub = for { s <- sub; n <- cityName; p <- resolveCity(n, s.code) } yield p
    val cityPlace = inSub.orElse(cityName.flatMap(n => resolveCity(n, countryPlace.code)))

    // A city that resolved only OUTSIDE the stated region, while
    // carrying a region of its own, says the region was wrong. A city
    // with no region at all says only that our table never linked it.
    val contradiction = for {
      s <- sub if inSub.isEmpty
      p <- cityPlace
      owner <- ancestors(p.code).find(_.kind == PlaceKind.Subdivision)
      if owner.code != s.code
      stated <- regionName
    } yield s"$stated (${p.name} is in ${owner.name})"

    val unresolved =
      regionName.filter(_ => sub.isEmpty).toList ++
      cityName.filter(_ => cityPlace.isEmpty).toList ++
      contradiction.toList

    ResolvedPlace(cityPlace.orElse(sub).getOrElse(countryPlace).code, unresolved)
  }

  /** Keep only codes this vocabulary knows. The validation gate. */
  def validate(codes: Iterable[String]): Set[String] = codes.filter(contains).toSet

  def size: Int = byCode.size

  // GeoNames continent code per country ("JP" -> "AS"); the third column
  // of countries.tsv, blank for none.
  private lazy val continents: Map[String, String] =
    loadTsv(s"$CountriesPath.tsv", 3)(cols => cols(0) -> cols(2)).filter(_._2.nonEmpty).toMap

  /**
   * The continent (GeoNames code: AF, AN, AS, EU, NA, OC, SA) a place is
   * in, from its country — `GN1860243` (Kanazawa) → `AS`. None for an
   * unknown code.
   */
  def continentOf(code: String): Option[String] = (byCode.get(code).toList ++ ancestors(code))
    .find(_.kind == PlaceKind.Country)
    .flatMap(c => continents.get(c.code))

  /**
   * Enclosing places, nearest first: `GN1860672` → `[JP-14, JP]`.
   * Excludes the place itself. Cycle-guarded — a malformed table must
   * degrade, not hang.
   */
  def ancestors(code: String): List[Place] = {
    @tailrec
    def loop(current: Option[String], seen: Set[String], acc: List[Place]): List[Place] =
      current.flatMap(byCode.get) match {
        case Some(p) if !seen.contains(p.code) => loop(p.parent, seen + p.code, p :: acc)
        case _                                 => acc.reverse
      }
    byCode.get(code).map(p => loop(p.parent, Set(code), Nil)).getOrElse(Nil)
  }

  /**
   * Expand places to (themselves ∪ their ancestors), keeping the MINIMUM
   * hop distance for each: 0 = named directly, 1 = parent, 2 =
   * grandparent. Mirrors `AuctioneerEntity.expandWithHops` so the two
   * vocabularies decay relevance the same way.
   *
   * Unknown codes contribute nothing — validation is not this method's
   * job, but it must not invent nodes either.
   */
  def expandWithHops(codes: Iterable[String]): Map[String, Int] =
    codes.iterator
      .filter(contains)
      .flatMap(c => (c, 0) +: ancestors(c).zipWithIndex.map { case (p, i) => (p.code, i + 1) })
      .toVector
      .groupMapReduce(_._1)(_._2)(math.min)

  /**
   * Does a campaign's targeting set match a piece of inventory?
   *
   * The inventory side is expanded to ancestors, the targeting side is
   * not. That asymmetry IS the rule: targeting `{JP}` matches a site
   * declaring Kamakura (JP is one of its ancestors), while targeting
   * `{JP-13}` does NOT match inventory that only says `JP` — no
   * descendant match, matching how category targeting already behaves.
   * An advertiser who wants both writes `{JP-13, JP}`.
   *
   * Two boundary cases, both load-bearing:
   *   - empty targeting matches everything (the contextual default,
   *     same as an empty `siteAllowlist`)
   *   - non-empty targeting does NOT match empty inventory. Undeclared
   *     is UNKNOWN, not "everywhere" — see the tier-2 section of
   *     docs/design/GEOGRAPHIC_CONTEXT.md. This falls out of the
   *     expansion rather than needing its own branch, but it is the
   *     rule most likely to be "fixed" by mistake.
   */
  def targetingMatches(targeting: Set[String], inventory: Set[String]): Boolean =
    targeting.isEmpty || expandWithHops(inventory).keysIterator.exists(targeting.contains)

  /**
   * How far a targeting set sits from a piece of inventory, or None when it
   * does not match at all.
   *
   * `Some(0)` means the inventory names a targeted place directly;
   * `Some(1)` its parent; and so on. Untargeted is `Some(0)` — no
   * constraint is a perfect fit, not a distant one, or every untargeted
   * campaign would be quietly penalised.
   *
   * The distinction from [[targetingMatches]] is what the caller does with
   * it: audience targeting is a binary gate, while CONTENT place targeting
   * is relevance, and relevance decays with distance. A campaign targeting
   * Japan on an article about Kamakura is a worse fit than one targeting
   * Kamakura, and should lose to it.
   */
  def matchHops(targeting: Set[String], inventory: Set[String]): Option[Int] =
    if (targeting.isEmpty) Some(0)
    else {
      val expanded = expandWithHops(inventory)
      targeting.iterator.flatMap(expanded.get).minOption
    }

  /** Localized display name for `code` in `lang`, if translated. */
  def nameIn(lang: String, code: String): Option[String] =
    localized.get(LocalizedNames.primary(lang)).flatMap(_.get(code))

  /** Localized name when we have one, else the canonical English name, else the code. */
  def displayName(lang: String, code: String): String =
    nameIn(lang, code).orElse(byCode.get(code).map(_.name)).getOrElse(code)

  /**
   * Type-ahead over English and localized names, for the publisher's
   * audience declaration and the advertiser's targeting picker — both
   * sides pick from the same vocabulary so neither has to type a code.
   *
   * Prefix matches rank above substring matches; within a rank, larger
   * places first (population for cities, and countries/subdivisions
   * ahead of cities since their population is 0 but they are broader).
   */
  def search(query: String, limit: Int = 20): List[Place] = {
    val direct = searchExact(query, limit)
    // Japanese place names are typed with their administrative suffix
    // (石川県, 豊岡市) while the tables carry the bare name (石川, 豊岡) —
    // the same tolerance `resolveCity` extends to the classifier.
    if (direct.nonEmpty) direct
    else
      stripAdminSuffix(query.trim) match {
        case Some(bare) => searchExact(bare, limit)
        case None       => direct
      }
  }

  private val AdminSuffixes = "都道府県市町村区"

  private def stripAdminSuffix(s: String): Option[String] =
    if (s.length > 1 && AdminSuffixes.contains(s.last)) Some(s.dropRight(1)) else None

  private def searchExact(query: String, limit: Int): List[Place] = {
    val q = normalize(query)
    if (q.isEmpty) Nil
    else {
      val kindRank = (p: Place) =>
        p.kind match {
          case PlaceKind.Country     => 0
          case PlaceKind.Subdivision => 1
          case PlaceKind.City        => 2
        }
      searchIndex.iterator
        .collect { case (name, p) if name.startsWith(q) => (0, p) }
        .++(searchIndex.iterator.collect { case (name, p) if !name.startsWith(q) && name.contains(q) => (1, p) })
        .toVector
        .distinctBy { case (rank, p) => (rank, p.code) }
        .sortBy { case (rank, p) => (rank, kindRank(p), -p.population, p.name) }
        .map(_._2)
        .distinctBy(_.code)
        .take(limit)
        .toList
    }
  }

  /** Diacritic- and punctuation-insensitive key, matching the build script. */
  private def normalize(s: String): String = {
    val decomposed = java.text.Normalizer
      .normalize(s, java.text.Normalizer.Form.NFD)
      .toLowerCase
      // NFD splits diacritics into combining marks, which are not
      // letters or digits — so this one filter drops accents and
      // punctuation together. Kana voicing marks are the exception:
      // dropping them makes パリ (Paris) and バリ (Bali) the same word.
      .filter(c => c.isLetterOrDigit || c == '\u3099' || c == '\u309A')
    java.text.Normalizer.normalize(decomposed, java.text.Normalizer.Form.NFC)
  }

  private def loadTsv[A](resourcePath: String, minCols: Int)(build: Array[String] => A): Vector[A] =
    Option(getClass.getResourceAsStream(resourcePath)) match {
      case None =>
        // A missing table is a packaging fault, not a runtime condition —
        // every geographic value would silently fail validation.
        throw new IllegalStateException(s"Place table missing from the classpath: $resourcePath")
      case Some(is) =>
        Using(Source.fromInputStream(is, "UTF-8")) { source =>
          source
            .getLines()
            .drop(1) // header
            .filter(_.nonEmpty)
            .map(_.split("\t", -1))
            .filter(_.length >= minCols)
            .map(build)
            .toVector
        }.get
    }
}
